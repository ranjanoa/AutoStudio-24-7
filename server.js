// Push an existing library video to YouTube
app.post('/api/videos/:id/push-to-youtube', (req, res) => {
  const { id } = req.params;
  const videos = readJsonFile(DB_FILE, []);
  const videoIndex = videos.findIndex(v => v.id === id);

  if (videoIndex === -1) {
    return res.status(404).json({ success: false, error: "Video record not found." });
  }

  const video = videos[videoIndex];
  
  // Resolve actual MP4 path
  let videoPath = video.videoPath;
  if (!videoPath || !fs.existsSync(videoPath)) {
    videoPath = path.join(STORAGE_DIR, 'output_videos', `${video.id}.mp4`);
  }

  if (!fs.existsSync(videoPath)) {
    return res.status(404).json({ success: false, error: `MP4 video file not found on disk at: ${videoPath}` });
  }

  addLog(`Initiating manual push to YouTube for: "${video.title}" (${video.id})`, "info");

  const fullDescription = `${video.hook || video.title}\n\n${video.affiliateNote || ''}\n\n#shorts #${video.genreId || 'viral'} #animation`;
  const tagsList = Array.isArray(video.tags) ? video.tags.join(',') : 'shorts,autostudio';
  const privacy = video.privacy || 'public';

  const pyArgs = [
    path.join(BASE_DIR, 'video_engine', 'youtube_uploader.py'),
    videoPath,
    '--title', video.title,
    '--description', fullDescription,
    '--privacy', privacy,
    '--tags', tagsList
  ];

  const pyProcess = spawn('python', ['-u', ...pyArgs], { cwd: BASE_DIR });

  let outputData = '';
  pyProcess.stdout.on('data', data => {
    const text = data.toString().trim();
    outputData += text + '\n';
    addLog(`[Uploader] ${text}`, "info");
  });

  pyProcess.stderr.on('data', data => {
    const text = data.toString().trim();
    addLog(`[Uploader Log] ${text}`, "warning");
  });

  pyProcess.on('close', code => {
    if (code === 0) {
      // Extract video ID from output: "[YouTube Upload Success] Video ID: <id>"
      const idMatch = outputData.match(/Video ID:\s*([a-zA-Z0-9_-]+)/i);
      const ytId = idMatch ? idMatch[1] : null;

      if (ytId && !ytId.startsWith('sim_')) {
        const youtubeUrl = `https://www.youtube.com/watch?v=${ytId}`;
        video.status = 'uploaded';
        video.youtubeUrl = youtubeUrl;
        video.uploadedAt = new Date().toISOString();

        // Update record in database
        videos[videoIndex] = video;
        writeJsonFile(DB_FILE, videos);

        addLog(`✨ Video successfully pushed to YouTube: ${youtubeUrl}`, "success");
        return res.json({ success: true, video, youtubeUrl });
      } else {
        addLog(`Upload returned simulated or unrecognized ID: ${ytId || outputData}`, "warning");
        return res.status(500).json({ success: false, error: "Upload failed to return valid YouTube video ID." });
      }
    } else {
      addLog(`Manual push to YouTube failed with exit code ${code}`, "error");
      return res.status(500).json({ success: false, error: `Uploader failed with exit code ${code}` });
    }
  });
});


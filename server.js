// Continuous Automation Engine Loop Manager
let automationTimer = null;

function runContinuousCycle() {
  if (!automationState.active) return;

  sanitizeSelectedGenres();
  const genres = automationState.selectedGenres;
  if (!genres || genres.length === 0) {
    addLog("No active genres available for continuous automation loop. Please configure genres in Genre Hub.", "warning");
    return;
  }

  let selectedGenre = genres[0];
  if (automationState.strategy === 'random') {
    selectedGenre = genres[Math.floor(Math.random() * genres.length)];
  } else {
    selectedGenre = genres[automationState.currentGenreIndex % genres.length];
    automationState.currentGenreIndex++;
  }

  addLog(`🤖 [Continuous Loop] Triggering auto-build cycle for Genre: ${selectedGenre.toUpperCase()}`, "info");

  const pyArgs = [
    path.join(BASE_DIR, 'video_engine', 'generator.py'),
    '--genre', selectedGenre,
    '--privacy', automationState.privacy
  ];
  if (automationState.autoUpload) pyArgs.push('--upload');
  if (automationState.noMusic) pyArgs.push('--nomusic');
  if (automationState.noVoice) pyArgs.push('--novoice');
  if (automationState.scenes && automationState.scenes !== 4) pyArgs.push('--scenes', automationState.scenes.toString());
  if (automationState.language) pyArgs.push('--language', automationState.language);

  const pyProcess = spawn('python', ['-u', ...pyArgs], { cwd: BASE_DIR });

  pyProcess.stdout.on('data', (data) => {
    addLog(`[Auto-Engine] ${data.toString().trim()}`, "info");
  });

  pyProcess.stderr.on('data', (data) => {
    addLog(`[Auto-Engine Log] ${data.toString().trim()}`, "warning");
  });

  pyProcess.on('close', (code) => {
    automationState.lastRunTime = new Date().toISOString();
    automationState.totalAutoGenerated++;
    const nextMs = automationState.intervalMinutes * 60 * 1000;
    automationState.nextRunTime = new Date(Date.now() + nextMs).toISOString();
    writeJsonFile(AUTOMATION_FILE, automationState);

    if (code === 0) {
      addLog(`✨ [Continuous Loop] Video cycle finished successfully! Next run at ${new Date(automationState.nextRunTime).toLocaleTimeString()}`, "success");
    } else {
      addLog(`⚠️ [Continuous Loop] Cycle ended with code ${code}. Rescheduling next run...`, "warning");
    }
  });
}

app.post('/api/automation/toggle', (req, res) => {
  const { active, intervalMinutes, strategy, privacy, autoUpload, selectedGenres, noMusic, noVoice, scenes, language } = req.body;

  automationState.active = !!active;
  if (intervalMinutes !== undefined) automationState.intervalMinutes = Math.max(1, parseInt(intervalMinutes));
  if (strategy) automationState.strategy = strategy;
  if (privacy) automationState.privacy = privacy;
  if (autoUpload !== undefined) automationState.autoUpload = !!autoUpload;
  if (selectedGenres) automationState.selectedGenres = selectedGenres;
  if (noMusic !== undefined) automationState.noMusic = !!noMusic;
  if (noVoice !== undefined) automationState.noVoice = !!noVoice;
  if (scenes !== undefined) automationState.scenes = parseInt(scenes);
  if (language !== undefined) automationState.language = language;

  sanitizeSelectedGenres();
  writeJsonFile(AUTOMATION_FILE, automationState);

  if (automationTimer) {
    clearInterval(automationTimer);
    automationTimer = null;
  }

  if (automationState.active) {
    addLog(`▶️ Continuous Automation System STARTED. Running every ${automationState.intervalMinutes} mins.`, "success");
    // Trigger initial run immediately
    runContinuousCycle();
    
    // Schedule repeating timer
    automationTimer = setInterval(() => {
      runContinuousCycle();
    }, automationState.intervalMinutes * 60 * 1000);

    const nextMs = automationState.intervalMinutes * 60 * 1000;
    automationState.nextRunTime = new Date(Date.now() + nextMs).toISOString();
    writeJsonFile(AUTOMATION_FILE, automationState);
  } else {
    addLog(`⏸️ Continuous Automation System STOPPED.`, "info");
    automationState.nextRunTime = null;
    writeJsonFile(AUTOMATION_FILE, automationState);
  }

  res.json({ success: true, automation: automationState });
});


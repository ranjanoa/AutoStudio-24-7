function readJsonFile(filePath, fallback = []) {
  if (fs.existsSync(filePath)) {
    try {
      return JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch (e) {
      console.error(`Error reading ${filePath}:`, e);
    }
  }
  return fallback;
}

function writeJsonFile(filePath, data) {
  try {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  } catch (e) {
    console.error(`Error writing ${filePath}:`, e);
  }
}

function getValidGenreIds() {
  const genres = readJsonFile(GENRES_FILE, []);
  return genres.map(g => g.id);
}

// In-Memory Automation State & System Logs
const savedAutomation = readJsonFile(AUTOMATION_FILE, null);
const validGenreIds = getValidGenreIds();

let automationState = {
  active: false,
  intervalMinutes: 15,
  strategy: 'sequential', // 'sequential', 'random'
  privacy: 'unlisted',
  autoUpload: true,
  selectedGenres: validGenreIds.length > 0 ? validGenreIds : [],
  currentGenreIndex: 0,
  lastRunTime: null,
  nextRunTime: null,
  totalAutoGenerated: 0,
  language: 'en',
  ...(savedAutomation || {})
};

function sanitizeSelectedGenres() {
  const currentValid = getValidGenreIds();
  if (currentValid.length > 0) {
    const filtered = (automationState.selectedGenres || []).filter(id => currentValid.includes(id));
    automationState.selectedGenres = filtered.length > 0 ? filtered : [currentValid[0]];
  } else {
    automationState.selectedGenres = [];
  }
}
sanitizeSelectedGenres();

let systemLogs = [
  { timestamp: new Date().toISOString(), message: "YouTube Continuous Automation System Initialized.", level: "info" }
];

function addLog(message, level = "info") {
  const logItem = { timestamp: new Date().toISOString(), message, level };
  systemLogs.unshift(logItem);
  if (systemLogs.length > 200) systemLogs.pop();
  console.log(`[${logItem.timestamp}] [${level.toUpperCase()}] ${message}`);
}

// System Status Endpoint
app.get('/api/status', (req, res) => {
  sanitizeSelectedGenres();
  const videos = readJsonFile(DB_FILE, []);
  const genres = readJsonFile(GENRES_FILE, []);

  const genreStats = {};
  genres.forEach(g => { genreStats[g.id] = 0; });
  videos.forEach(v => {
    if (genreStats[v.genreId] !== undefined) {
      genreStats[v.genreId]++;
    } else {
      genreStats[v.genreId] = 1;
    }
  });

  res.json({
    totalVideos: videos.length,
    uploadedCount: videos.filter(v => v.status === 'uploaded').length,
    simulatedCount: videos.filter(v => v.status === 'uploaded_simulated').length,
    automation: automationState,
    genreStats,
    hasOAuthSecrets: fs.existsSync(SECRETS_FILE),
    hasOAuthToken: fs.existsSync(TOKEN_FILE),
    hasLlmKey: fs.existsSync(ENV_FILE)
  });
});


app.post('/api/generate', (req, res) => {
  const { genreId, topic, privacy = 'unlisted', autoUpload = true, noMusic = false, noVoice = false, scenes = 4, language = 'en' } = req.body;

  addLog(`Manual video generation requested: Genre [${genreId}], Topic [${topic || 'Default'}]`, "info");

  const pyArgs = [
    path.join(BASE_DIR, 'video_engine', 'generator.py'),
    '--genre', genreId || 'history',
    '--privacy', privacy
  ];
  if (topic) pyArgs.push('--topic', topic);
  if (autoUpload) pyArgs.push('--upload');
  if (noMusic) pyArgs.push('--nomusic');
  if (noVoice) pyArgs.push('--novoice');
  if (scenes && scenes !== 4) pyArgs.push('--scenes', scenes.toString());
  if (language) pyArgs.push('--language', language);

  const pyProcess = spawn('python', ['-u', ...pyArgs], { cwd: BASE_DIR });

  let outputData = '';
  pyProcess.stdout.on('data', (data) => {
    const text = data.toString().trim();
    outputData += text + '\n';
    addLog(`[Engine] ${text}`, "info");
  });

  pyProcess.stderr.on('data', (data) => {
    const text = data.toString().trim();
    addLog(`[Engine Log] ${text}`, "warning");
  });

  pyProcess.on('close', (code) => {
    if (code === 0) {
      addLog(`Video generation completed successfully for genre [${genreId}]`, "success");
      const videos = readJsonFile(DB_FILE, []);
      res.json({ success: true, latestVideo: videos[0] || null });
    } else {
      addLog(`Video generation process failed with code ${code}`, "error");
      res.status(500).json({ success: false, error: `Engine exited with code ${code}` });
    }
  });
});


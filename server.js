let currentAuthProcess = null;

// Launch YouTube OAuth authorization browser flow
app.post('/api/youtube/authorize', async (req, res) => {
  if (!fs.existsSync(SECRETS_FILE)) {
    return res.status(400).json({ success: false, error: "client_secrets.json not found. Please save Client ID and Client Secret first." });
  }

  // Terminate any previous hanging auth process
  if (currentAuthProcess) {
    try { currentAuthProcess.kill(); } catch (e) {}
    currentAuthProcess = null;
  }

  const oauthUrlFile = path.join(STORAGE_DIR, 'oauth_url.txt');
  if (fs.existsSync(oauthUrlFile)) {
    try { fs.unlinkSync(oauthUrlFile); } catch (e) {}
  }

  addLog("Initiating YouTube OAuth login flow...", "info");
  currentAuthProcess = spawn('python', ['-u', path.join(BASE_DIR, 'video_engine', 'auth_youtube.py')], { cwd: BASE_DIR });

  currentAuthProcess.stdout.on('data', data => {
    addLog(`[OAuth Flow] ${data.toString().trim()}`, "info");
  });

  currentAuthProcess.stderr.on('data', data => {
    addLog(`[OAuth Log] ${data.toString().trim()}`, "warning");
  });

  currentAuthProcess.on('close', code => {
    currentAuthProcess = null;
    if (code === 0) {
      addLog("YouTube Channel authorized and connected successfully!", "success");
    } else {
      addLog(`OAuth authorization process closed (code: ${code})`, "info");
    }
  });

  // Wait for auth_youtube.py to write the Google OAuth URL (up to 4s)
  let authUrl = null;
  for (let i = 0; i < 20; i++) {
    await new Promise(r => setTimeout(r, 200));
    if (fs.existsSync(oauthUrlFile)) {
      try {
        const content = fs.readFileSync(oauthUrlFile, 'utf8').trim();
        if (content.startsWith('http')) {
          authUrl = content;
          break;
        }
      } catch (e) {}
    }
  }

  if (authUrl) {
    res.json({ success: true, authUrl, message: "Authorization URL generated successfully." });
  } else {
    res.status(500).json({ success: false, error: "Failed to generate authorization URL." });
  }
});

